"""Leave-one-day-out versions of the registered Nasdaq stock tests (review round 4, R5; exploratory, post hoc).

    python experiments/day_jackknife.py [--dir supplement/registered_tests]

For each sealed stage and each of H1-H9, drop one test day at a time and redo the registered estimator on the
remaining days: per-stock means of the paired differences (episodes weighted equally within a stock), the stock
bootstrap stratified by relative-tick tercile (10,000 replicates, seed 0, 90% intervals), and the registered test read
from its interval (equivalence within +-0.015; 'greater' and 'less' against zero). Reported: the range of the
leave-one-day-out estimates and how many of the leave-one-out decisions agree with the registered one. Holm and the
tercile conditions of H1 are not reapplied (H1's tercile intervals are reported by the registered analysis). Computed
from the supplement's stock-day cells; reads no sealed table.
Writes results/transfer/day_jackknife.json and paper/numbers_day_jackknife.tex.
"""

from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd

from invex.eval.stats import cluster_bootstrap
from invex.paths import REPO, RESULTS

STAGES = {"StageOne": "confirm_stage1_stocks", "StageTwo": "confirm_stage2_stocks"}
TEST = {"H1": "tost", "H2": "greater", "H3": "greater", "H4": "greater", "H5": "tost", "H6": "less", "H7": "greater",
        "H8": "tost", "H9": "greater"}
DELTA = 0.015
MAC = {f"H{i}": f"H{w}" for i, w in zip(range(1, 10), ("One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight",
                                                         "Nine"))}


def decide(test: str, lo: float, hi: float) -> bool:
    return {"tost": -DELTA < lo and hi < DELTA, "greater": lo > 0, "less": hi < 0}[test]


def estimate(c: pd.DataFrame, terc: pd.Series) -> dict:
    t = c.groupby("stock")[["sum", "n"]].sum()
    m = t["sum"] / t["n"]
    r = cluster_bootstrap(m.to_numpy(), terc.reindex(m.index).to_numpy(), n_boot=10_000, level=0.90)
    return {"mean": float(r["mean"]), "lo": float(r["lo"]), "hi": float(r["hi"]), "stocks": int(len(m))}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(REPO / "supplement" / "registered_tests"))
    a = ap.parse_args()
    cells = pd.read_parquet(f"{a.dir}/cells.parquet")
    stocks = pd.read_parquet(f"{a.dir}/stocks.parquet")
    out, m, agree_all, total_all = {}, {}, 0, 0
    for tag, stem in STAGES.items():
        days = sorted(cells.loc[cells["analysis"] == stem, "day"].unique())
        for h, test in TEST.items():
            c = cells[(cells["analysis"] == stem) & (cells["hypothesis"] == h)]
            terc = stocks[(stocks["analysis"] == stem) & (stocks["hypothesis"] == h)].set_index("stock")["tercile"]
            full = estimate(c, terc)
            full["holds"] = decide(test, full["lo"], full["hi"])
            loo = {}
            for d in days:
                r = estimate(c[c["day"] != d], terc)
                r["holds"] = decide(test, r["lo"], r["hi"])
                loo[str(d)] = r
            agree = sum(r["holds"] == full["holds"] for r in loo.values())
            agree_all += agree
            total_all += len(loo)
            est = [r["mean"] for r in loo.values()]
            out[f"{tag}{h}"] = {"full": full, "leave_one_out": loo, "agree": agree}
            k = f"DayJk{tag}{MAC[h]}"
            m[k + "Min"], m[k + "Max"] = f"{min(est):+.3f}", f"{max(est):+.3f}"
            m[k + "Agree"] = f"{agree} of {len(loo)}"
            print(f"{tag} {h} ({test}): full {full['mean']:+.4f} [{full['lo']:+.4f}, {full['hi']:+.4f}] "
                  f"{'holds' if full['holds'] else 'no'}; leave-one-day-out {min(est):+.4f}..{max(est):+.4f}, "
                  f"{agree}/{len(loo)} agree; lost on {[d for d, r in loo.items() if r['holds'] != full['holds']]}")
    m["DayJkAgree"], m["DayJkTotal"] = str(agree_all), str(total_all)
    (RESULTS / "transfer" / "day_jackknife.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/day_jackknife.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_day_jackknife.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
