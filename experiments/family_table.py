"""Table of the stock contrasts by task family (paper/tab_family.tex), from results/transfer/family_contrasts.json
(experiments/family_contrasts.py); reads no sealed table.

    python experiments/family_table.py
"""

from __future__ import annotations

import json

from invex.paths import REPO, RESULTS

NAMES = {"H2": "raw units lose (H2)", "H3": "z-scores lose to \\Rmst{} (H3)", "H4": "descriptors do not substitute (H4)",
         "H6": "tick context helps (H6)"}
FAMS = (("MS", "microstructure"), ("KO", "Kyle--Obizhaeva"), ("P", "physical"))


def main() -> None:
    d = json.loads((RESULTS / "transfer" / "family_contrasts.json").read_text())
    rows = ["% generated by experiments/family_table.py (post hoc) -- do not edit",
            "\\begin{tabular}{@{}l" + "r" * 6 + "@{}}", "\\toprule",
            " & \\multicolumn{3}{c}{Stage 1 (2020--21)} & \\multicolumn{3}{c}{Stage 2 (2025--26)} \\\\",
            "task family & " + " & ".join(n for _, n in FAMS) + " & " + " & ".join(n for _, n in FAMS) + " \\\\",
            "episodes & " + " & ".join(f"{d[s][f]['episodes']:,}".replace(",", "{,}") for s in ("stage1", "stage2")
                                      for f, _ in FAMS) + " \\\\", "\\midrule"]
    for h, name in NAMES.items():
        cells = []
        for s in ("stage1", "stage2"):
            for f, _ in FAMS:
                e = d[s][f][h]
                cells.append(f"${e['mean']:+.3f}$ {{\\scriptsize[${e['lo']:+.3f}$, ${e['hi']:+.3f}$]}}")
        rows.append(name + " & " + " & ".join(cells) + " \\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    (REPO / "paper" / "tab_family.tex").write_text("\n".join(rows) + "\n")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
