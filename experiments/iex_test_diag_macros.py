"""Paper macros for the post hoc diagnosis of the prospective IEX test, from results/transfer/iex_test_diagnostics.json
(written by experiments/iex_test_diagnostics.py; this script reads no sealed table).

    python experiments/iex_test_diag_macros.py

The stock-weighted estimate gives each stock 1/(stocks) of the weight, spread over its days; the most influential
stock-day of I3 is reported with its policies' costs, and each fitted-Q estimate is recomputed without that stock
(arithmetic on the stored means, no bootstrap). Writes paper/numbers_iex_diag.tex.
"""

from __future__ import annotations

import json

from invex.paths import REPO, RESULTS

LETTERS = {"1": "One", "2": "Two", "3": "Three"}


def main() -> None:
    d = json.loads((RESULTS / "transfer" / "iex_test_diagnostics.json").read_text())
    t = d["tests"]
    top = t["I3"]["top_stock_days"][0]  # the stock-day with the largest influence on the stock-weighted I3
    stock, day, n = top["stock"], top["day"], t["I3"]["stocks"]
    w = top["worst"][0]
    zero = [x["c_spread"] for x in w["policies"]["zero:R3tick"]]
    m = {"IexDiagStock": stock, "IexDiagDay": day, "IexDiagEpisodes": str(top["episodes"]),
         "IexDiagDaysOfStock": str(top["days_of_stock"]), "IexDiagQ": str(w["Q"]),
         "IexDiagSide": "sell" if w["side"] < 0 else "buy", "IexDiagSpreadTicks": f"{w['w_spread_ticks']:.1f}",
         "IexDiagCostZero": f"{max(zero):.1f}",
         "IexDiagShortfall": str(max(x["shortfall"] for x in w["policies"]["zero:R3tick"])),
         "IexDiagWeight": f"{t['I3']['episodes'] / n / top['episodes']:,.0f}".replace(",", "{,}")}
    for hid in ("I1", "I2", "I3"):
        r = t[hid]
        sd = next(x for x in r["top_stock_days"] if x["stock"] == stock and x["day"] == day)
        if sd["days_of_stock"] != 1:
            raise SystemExit("the influential stock is on more than one day: recompute without it properly")
        without = (r["by_stock"] * n - sd["mean"]) / (n - 1)
        k = "IexDiag" + "I" + LETTERS[hid[1]]
        m[k + "Stock"] = f"{r['by_stock']:+.3f}"
        m[k + "Episode"] = f"{r['by_episode']:+.3f}"
        m[k + "Without"] = f"{without:+.3f}"
        m[k + "Diff"] = f"{sd['mean']:+.1f}"
        m[k + "Share"] = f"{100 * sd['contribution'] / r['by_stock']:.0f}\\%"
    other = [x["c_spread"] for x in t["I2"]["top_stock_days"][0]["worst"][0]["policies"].get("iexseen:R3tick", [])]
    m["IexDiagSeenSame"] = str(sum(abs(c - max(zero)) < 1e-6 for c in other))
    m["IexDiagImmediate"] = f"{t['I1']['top_stock_days'][0]['worst'][0]['policies']['base:immediate'][0]['c_spread']:.2f}"
    # the registered day-by-day reading (iex-v1, secondary analysis 6) under both estimands, and leaving each day out
    rows = ["% generated by experiments/iex_test_diag_macros.py (post hoc) -- do not edit",
            "\\begin{tabular}{@{}lrrrrrrrr@{}}", "\\toprule",
            " & \\multicolumn{2}{c}{I1} & \\multicolumn{2}{c}{I2} & \\multicolumn{2}{c}{I3} & \\multicolumn{2}{c}{I3, day left out} \\\\",
            "day & (a) & (b) & (a) & (b) & (a) & (b) & (a) & (b) \\\\", "\\midrule"]
    for day in t["I1"]["by_day"]:
        c = [t[h]["by_day"][day][e] for h in ("I1", "I2", "I3") for e in ("by_stock", "by_episode")]
        lo = t["I3"]["leave_one_day_out"][day]
        c += [lo["by_stock"], lo["by_episode"]]
        rows.append(day + " & " + " & ".join(f"${x:+.3f}$" for x in c) + " \\\\")
    pooled = [t[h][e] for h in ("I1", "I2", "I3") for e in ("by_stock", "by_episode")]
    rows += ["\\midrule", "all days & " + " & ".join(f"${x:+.3f}$" for x in pooled) + " & & \\\\",
             "\\bottomrule", "\\end{tabular}"]
    (REPO / "paper" / "tab_iex_days.tex").write_text("\n".join(rows) + "\n")
    lines = ["% generated by experiments/iex_test_diag_macros.py (post hoc) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_iex_diag.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
