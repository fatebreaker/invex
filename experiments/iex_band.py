"""The IEX tests without episodes a price band would have stopped (review round 4, R2; exploratory, post hoc).

    python experiments/iex_band.py [--band-bps 500]

The single-venue replay can walk a forced cross into quotes far from the market, which order protection, and Limit
Up-Limit Down bands (5% or 10% from the recent average price at most times of day for stocks above $3), would have
kept a real order from reaching. Changing the replay would change the registered evaluation; instead this drops
every one-tick episode in which some evaluated policy paid more than --band-bps basis points of the price per share
(500: 5%, the narrower band), and reruns the registered estimators on the rest: I1-I3, P1-P3, P4, L1, L2, each under
estimand (a) (stocks and their days weighted equally; two-way bootstrap of the registered analysis) and (b) (episodes
weighted equally), 95% intervals, the registered test and margin, Holm within the family at 2.5%. From the stored
evaluations of the one-tick population (the whole table iex_test_v0), so no sealed table is read.
Writes results/transfer/iex_band.json and paper/numbers_iex_band.tex.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from confirm import policy_costs  # noqa: E402
from iex_test_reanalysis import by_episode_table, by_stock_table, mac, test  # noqa: E402

from invex.eval.stats import holm  # noqa: E402
from invex.paths import REPO, RESULTS  # noqa: E402

FAMILIES = [("iex_test", "confirmatory_iex_v1.json", "iex"), ("iex_test_ppo", "confirmatory_iex_v2.json", "iex"),
            ("iex_test_ppo", "confirmatory_iex_v2.json", "iexlearner"), ("iex_test_v8", "confirmatory_iex_v8.json", "iexlm")]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--band-bps", type=float, default=500.0)
    ap.add_argument("--n-boot", type=int, default=10_000)
    a = ap.parse_args()
    out, m, flagged_all = {"band_bps": a.band_bps, "families": {}}, {}, set()
    for ev, spec_name, fam_name in FAMILIES:
        spec = json.loads((REPO / "prereg" / spec_name).read_text())
        fam = spec["families"][fam_name]
        res = pd.read_parquet(RESULTS / "transfer" / f"eval_{ev}.parquet",
                              columns=["key", "policy", "excluded", "stock", "day", "c_bps", fam["unit"]])
        res = res[~res["excluded"]]
        flagged = set(res.loc[res["c_bps"] > a.band_bps, "key"])
        flagged_all |= flagged
        per = policy_costs(res, fam["unit"], "seen")
        rows = []
        for h in fam["hypotheses"]:
            diff = (per[h["a"]] - per[h["b"]]).dropna()
            keys = diff.index.get_level_values("key")
            kept = diff[~keys.isin(flagged)]
            delta = h.get("delta", spec.get("delta", 0.0))
            r = {"id": h["id"], "test": h["test"], "delta": delta, "dropped": int(keys.isin(flagged).sum()),
                 "a": test(*by_stock_table(kept), h["test"], delta, a.n_boot),
                 "b": test(*by_episode_table(kept), h["test"], delta, a.n_boot)}
            rows.append(r)
        for est in ("a", "b"):
            for r, padj in zip(rows, holm([r[est]["p"] for r in rows])):
                r[est]["p_holm"] = float(padj)
                r[est]["holds"] = bool(padj < 0.025)
        out["families"][f"{ev}:{fam_name}"] = rows
        for r in rows:
            for est, tag in (("a", "Stock"), ("b", "Episode")):
                e = r[est]
                k = f"IexBand{mac(r['id'])}{tag}"
                m[k], m[k + "Lo"], m[k + "Hi"] = f"{e['mean']:+.3f}", f"{e['lo95']:+.3f}", f"{e['hi95']:+.3f}"
                m[k + "Held"] = "holds" if e["holds"] else "not shown"
                print(f"{r['id']} ({est}): {e['mean']:+.4f} [{e['lo95']:+.4f}, {e['hi95']:+.4f}] Holm p "
                      f"{e['p_holm']:.4f} {'holds' if e['holds'] else 'not shown'} (dropped {r['dropped']})")
    out["flagged_episodes"] = len(flagged_all)
    m["IexBandEpisodes"] = f"{len(flagged_all):,}".replace(",", "{,}")
    held = {est: [r["id"] for f in out["families"].values() for r in f if r[est]["holds"]] for est in ("a", "b")}
    m["IexBandHeldStock"], m["IexBandHeldEpisode"] = str(len(held["a"])), str(len(held["b"]))
    print(f"flagged episodes: {len(flagged_all)}; (a) holds {held['a']}; (b) holds {held['b']}")
    (RESULTS / "transfer" / "iex_band.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/iex_band.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_iex_band.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
