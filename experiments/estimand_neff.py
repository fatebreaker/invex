"""How many episodes each registered estimand effectively uses (review round 4; exploratory, from the supplement).

    python experiments/estimand_neff.py [--dir supplement/registered_tests]

Under estimand (a) every stock, and each of its days, is weighted equally, so an episode in stock-day (s, d) has weight
w = 1 / (S D_s n_sd), with S stocks, D_s days of stock s and n_sd episodes in the stock-day; under (b) every episode has
weight 1/N. Kish's effective sample size 1 / sum(w^2) is N for (b); for (a) it says how many equally weighted episodes
the estimate is worth, and the largest weight times N how many average episodes one episode counts for. Computed from
the stock-day counts of the registered analyses (H1 on Nasdaq, I2 on IEX). Reads no sealed table.
Writes results/transfer/estimand_neff.json and paper/numbers_estimand_neff.tex.
"""

from __future__ import annotations

import argparse
import json

import pandas as pd

from invex.paths import REPO, RESULTS

ANALYSES = {"StageOne": ("confirm_stage1_stocks", "H1"), "StageTwo": ("confirm_stage2_stocks", "H1"),
            "IexRetro": ("confirm_iex_retro_iex", "I2"), "IexTest": ("confirm_iex_test_iex", "I2")}


def neff(cells: pd.DataFrame) -> dict:
    S = cells["stock"].nunique()
    N = int(cells["n"].sum())
    D = cells.groupby("stock")["day"].transform("nunique")
    w = 1.0 / (S * D * cells["n"])
    n_eff = 1.0 / float((cells["n"] * w ** 2).sum())
    return {"stocks": int(S), "episodes": N, "n_eff": n_eff, "share": n_eff / N, "max_weight_ratio": float(w.max() * N)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(REPO / "supplement" / "registered_tests"))
    a = ap.parse_args()
    cells = pd.read_parquet(f"{a.dir}/cells.parquet")
    out, m = {}, {}
    for tag, (stem, h) in ANALYSES.items():
        r = neff(cells[(cells["analysis"] == stem) & (cells["hypothesis"] == h)])
        out[tag] = r
        m[f"Neff{tag}"] = f"{r['n_eff']:,.0f}".replace(",", "{,}")
        m[f"Neff{tag}Share"] = f"{100 * r['share']:.0f}\\%"
        m[f"Neff{tag}MaxWeight"] = f"{r['max_weight_ratio']:,.0f}".replace(",", "{,}")
        print(f"{tag}: {r}")
    (RESULTS / "transfer" / "estimand_neff.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/estimand_neff.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_estimand_neff.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
