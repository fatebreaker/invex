"""How much of the raw-unit loss the equal-information arm closes (review round 1; exploratory), from the stored
contrasts of experiments/info_arm.py (validation, Stage 1 and Stage 2): 1 - (R0info - R3tick) / (R0 - R3tick), per learner.
Reads no sealed table. Writes paper/numbers_info_share.tex.

    python experiments/info_share.py
"""

from __future__ import annotations

import json

from invex.paths import REPO, RESULTS


def main() -> None:
    m = {}
    for sfx, tag in (("", "Val"), ("_stage1", "StageOne"), ("_stage2", "StageTwo")):
        p = RESULTS / "transfer" / f"info_arm{sfx}.json"
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        for learner in ("Trees", "Nn", "Ppo"):
            info, raw = d.get(f"{learner}InfoVsMstick"), d.get(f"{learner}RawVsMstick")
            if info and raw and raw["mean"] > 0:
                share = 1 - info["mean"] / raw["mean"]
                m[f"InfoShare{tag}{learner}"] = f"{100 * share:.0f}\\%"
                print(tag, learner, f"{share:.1%}")
    lines = ["% generated by experiments/info_share.py (exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_info_share.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
