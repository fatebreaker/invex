"""What P4 measures (review round 2; exploratory, post hoc; no sealed read).

    python experiments/ot_ref.py

PPO trained by the zero-shot recipe on Nasdaq's one-tick books only (otppo: the 2019 training stocks and days,
w_onetick >= 0.5, subsampled to the size of train_v0) against zero-shot PPO (zeroppo, every 2019 book) and PPO trained
on IEX's one-tick books (ixppo, iex-v8), on the IEX test days' one-tick books (the whole table iex_test_v0, checked by
its size), under both IEX estimands, with stocks, days and each arm's three seeds resampled (95% intervals). If otppo
closes the gap of P4, the half margin is specialisation to one-tick books; if it does not, it is the venue or the years.
Writes results/transfer/ot_ref.json and paper/numbers_ot_ref.tex.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import iex_review2 as rv  # noqa: E402

from invex.paths import REPO, RESULTS  # noqa: E402

rv.ARMS["ot"] = "otppo_R3tick"
PAIRS = {"OtVsIx": ("ot", "ix"), "OtVsZero": ("ot", "zero"), "ZeroVsIx": ("zero", "ix")}
ONE_TICK_EPISODES = 688_404


def main() -> None:
    cols = ["key", "policy", "stock", "day", "c_spread", "excluded"]
    res = pd.concat([pd.read_parquet(RESULTS / "transfer" / f"eval_{e}.parquet", columns=cols)
                     for e in ("iex_test_v8", "iex_test_ot")], ignore_index=True)
    res = res[~res["excluded"] & res["policy"].str.contains("R3tick")].drop_duplicates(["key", "policy"])
    out, m = {}, {}
    for by, tag in (("stock", "Stock"), ("episode", "Episode")):
        arr, w, n_eps = rv.seed_tables(res, by)
        assert n_eps == ONE_TICK_EPISODES, n_eps
        for label, (x, y) in PAIRS.items():
            r = rv.boot(arr, w, x, y, by)
            out[f"{label}_{by}"] = r
            k = f"IexRevOt{label}{tag}"
            m[k], m[k + "Lo"], m[k + "Hi"] = f"{r['mean']:+.3f}", f"{r['lo']:+.3f}", f"{r['hi']:+.3f}"
            print(f"{label:9s} {by:8s} {r['mean']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}]")
    (RESULTS / "transfer" / "ot_ref.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/ot_ref.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_ot_ref.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
