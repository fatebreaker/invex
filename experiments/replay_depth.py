"""How often an order is larger than the displayed size at the opposite best on its venue (review round 1): the share
of training episodes whose order Q exceeds the visible size at the far touch at the first decision, so that crossing
then walks beyond the first price level of that one venue's book. Training transitions only (no sealed table).

    python experiments/replay_depth.py

Writes paper/numbers_replay_depth.tex.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from invex.env.features import F_FAR, F_Q
from invex.paths import DATA, REPO

SETS = {"Nasdaq": "train_v0", "IexOnetick": "iex_train_v1", "IexAll": "iexall_train_v0"}


def main() -> None:
    m = {}
    for label, name in SETS.items():
        z = np.load(DATA / "transitions" / name / "data.npz", mmap_mode="r")
        r0 = np.asarray(z["raw"][0])
        ratio = r0[:, F_Q] / np.maximum(r0[:, F_FAR], 1.0)
        fam = pd.read_parquet(DATA / "transitions" / name / "eps.parquet", columns=["family"])["family"].to_numpy()
        m[f"ReplayBeyond{label}"] = f"{100 * np.mean(ratio > 1):.0f}\\%"
        m[f"ReplayBeyond{label}Median"] = f"{np.median(ratio):.2f}"
        for f in ("P", "MS", "KO"):
            m[f"ReplayBeyond{label}{ {'P': 'Phys', 'MS': 'Ms', 'KO': 'Ko'}[f] }"] = f"{100 * np.mean(ratio[fam == f] > 1):.0f}\\%"
        print(label, name, {k: v for k, v in m.items() if k.startswith(f"ReplayBeyond{label}")})
    # how often the shortfall rule fires (a cross beyond the visible book) on the Nasdaq validation days
    from invex.paths import RESULTS
    r = pd.read_parquet(RESULTS / "transfer" / "eval_val_v0.parquet", columns=["key", "shortfall", "excluded"])
    r = r[~r["excluded"]]
    short = r.groupby("key")["shortfall"].max() > 0
    m["ReplayShortNasdaqVal"] = f"{int(short.sum())}"
    m["ReplayShortNasdaqValEpisodes"] = f"{len(short):,}".replace(",", "{,}")
    lines = ["% generated by experiments/replay_depth.py -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_replay_depth.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
