"""PPO against fitted Q-iteration on Stage 2 (review round 2; exploratory, post hoc, from stored evaluations only).

    python experiments/ppo_stage2.py

The registered tree policies (eval_stage2) and the Nasdaq-trained PPO policies scored on Stage 2 for the
equal-information arm (eval_stage2_info), in MS+tick and raw units: PPO minus fitted Q-iteration in each, and each
learner's raw-unit loss. Seeds averaged per episode, every stock weighted equally, stock bootstrap stratified by
relative-tick tercile, 95% intervals. Writes results/transfer/ppo_stage2.json and paper/numbers_ppo_stage2.tex.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd
import pyarrow.dataset as ds

from invex.eval.stats import cluster_bootstrap
from invex.eval.universe import load_splits
from invex.paths import REPO, RESULTS

ARMS = {"stage2": ("zero_R3tick", "zero_R0"), "stage2_info": ("zeroppo_R3tick", "zeroppo_R0")}
CONTRASTS = [("PpoStageTwoVsTreesMsTick", "zeroppo_R3tick", "zero_R3tick"), ("PpoStageTwoVsTreesRaw", "zeroppo_R0", "zero_R0"),
             ("PpoStageTwoRawVsMsTick", "zeroppo_R0", "zeroppo_R3tick"), ("TreesStageTwoRawVsMsTick", "zero_R0", "zero_R3tick")]


def main() -> None:
    parts = []
    for ev, arms in ARMS.items():
        pols = [f"{a}_s{s}" for a in arms for s in range(3)]
        t = ds.dataset(RESULTS / "transfer" / f"eval_{ev}.parquet").to_table(
            columns=["key", "policy", "stock", "c_spread", "excluded"], filter=ds.field("policy").isin(pols))
        parts.append(t.to_pandas())
    res = pd.concat(parts, ignore_index=True)
    res = res[~res["excluded"]].assign(arm=lambda r: r["policy"].str.replace(r"_s\d+$", "", regex=True))
    per = res.pivot_table(index=["key", "stock"], columns="arm", values="c_spread", aggfunc="mean").dropna()
    # the relative tick as the newer evaluation stores it (the registered one predates that column)
    e = ds.dataset(RESULTS / "transfer" / "eval_stage2_info.parquet").to_table(
        columns=["stock", "eta", "policy"], filter=ds.field("policy") == "zeroppo_R3tick_s0").to_pandas()
    eta = e.groupby("stock")["eta"].median()
    cuts = np.log(load_splits()["eta_sigma_tercile_cuts"])
    out, m = {}, {}
    for label, a, b in CONTRASTS:
        bs = (per[a] - per[b]).groupby(level="stock").mean()
        st = np.digitize(np.log(eta.reindex(bs.index).to_numpy()), cuts)
        r = cluster_bootstrap(bs.to_numpy(), st, n_boot=10_000, level=0.95)
        out[label] = {k: float(r[k]) for k in ("mean", "lo", "hi")}
        m[label], m[label + "Lo"], m[label + "Hi"] = f"{r['mean']:+.3f}", f"{r['lo']:+.3f}", f"{r['hi']:+.3f}"
        print(f"{label:26s} {r['mean']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}] ({len(bs)} stocks)")
    (RESULTS / "transfer" / "ppo_stage2.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/ppo_stage2.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_ppo_stage2.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
