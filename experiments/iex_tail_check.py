"""The cap sweep and tail counts of prereg/iex_capped_v5.md and App G, from a stored IEX evaluation (no policy is run,
and the sealed episode table is not loaded: the competitive-book tables hold only population episodes).

    python experiments/iex_tail_check.py --eval iex_retro

Per cap (none, 31, 20, 5, 1.33): I2 (Nasdaq-trained MS+tick fitted Q-iteration minus the IEX-trained policy), stocks
weighted equally and each stock's days equally, with the two-way bootstrap of the registered family (2,000
replicates, 90% interval). Then, for three policies, the upper quantiles of the per-episode cost and how many
episodes cost more than 31 and 100 spreads; and, by relative-tick tercile (the frozen cuts, each stock's median eta,
as in experiments/analyze_iex.py), each tercile's stocks, share of episodes and share of the stock-weighted I2 and
I3 estimates. Writes paper/numbers_iex_tail_<eval>.tex. Exploratory.
"""

from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from invex.eval.stats import pigeonhole_bootstrap
from invex.eval.universe import load_splits
from invex.paths import REPO, RESULTS

CAPS = (None, 31.0, 20.0, 5.0, 1.33)


def i2(res: pd.DataFrame, cap: float | None, n_boot: int, a: str = "zero_R3tick", b: str = "iexseen_R3tick") -> dict:
    r = res[res["arm"].isin([a, b])]
    c = r["c_spread"].clip(upper=cap) if cap else r["c_spread"]
    per = r.assign(c=c).groupby(["arm", "stock", "day", "key"])["c"].mean().unstack(0)
    d = (per[a] - per[b]).dropna()
    cm = d.groupby(level=["stock", "day"]).mean().unstack()
    w = cm.notna().astype(float)
    w = w.div(w.sum(axis=1), axis=0)
    return pigeonhole_bootstrap((cm.fillna(0.0) * w).to_numpy(), w.to_numpy(), n_boot=n_boot, level=0.90)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--eval", default="iex_retro")
    ap.add_argument("--n-boot", type=int, default=2000)
    a = ap.parse_args(argv)
    res = pd.read_parquet(RESULTS / "transfer" / f"eval_{a.eval}.parquet",
                          columns=["key", "policy", "stock", "day", "c_spread", "excluded", "eta"])
    res = res[~res["excluded"]]
    res["arm"] = res["policy"].str.replace(r"_s\d+$", "", regex=True)
    print(f"{a.eval}: {res['key'].nunique():,} episodes, {res['stock'].nunique()} stocks")
    print("| cap | I2 | 90% interval |\n|---|---|---|")
    for cap in CAPS:
        e = i2(res, cap, a.n_boot)
        print(f"| {cap if cap else 'none'} | {e['mean']:+.4f} | [{e['lo']:+.4f}, {e['hi']:+.4f}] |")
    print("\n| policy | p99 | p99.9 | max | > 31 | > 100 |\n|---|---|---|---|---|---|")
    macros = {}
    for p, lab in (("zero_R3tick_s0", "Zero"), ("iexseen_R3tick_s0", "Iex"), ("immediate", "Immediate")):
        x = res.loc[res["policy"] == p, "c_spread"]
        print(f"| {p} | {x.quantile(0.99):.2f} | {x.quantile(0.999):.1f} | {x.max():.1f} | {int((x > 31).sum())} | "
              f"{int((x > 100).sum())} |")
        macros.update({f"IexTail{lab}Max": f"{x.max():.0f}", f"IexTail{lab}OverThirtyOne": f"{int((x > 31).sum())}",
                       f"IexTail{lab}OverHundred": f"{int((x > 100).sum())}"})
    # where the stock-weighted estimates come from, by relative-tick tercile
    cuts = np.log(load_splits()["eta_sigma_tercile_cuts"])
    terc = pd.Series(np.digitize(np.log(res.groupby("stock")["eta"].median()), cuts),
                     index=res.groupby("stock")["eta"].median().index)
    per = res.groupby(["arm", "stock", "day", "key"])["c_spread"].mean().unstack(0)
    n_eps = per.groupby(level="stock").size()
    print("\n| tercile | stocks | episodes | share of I2 | share of I3 |\n|---|---|---|---|---|")
    for hid, x, y in (("ITwo", "zero_R3tick", "iexseen_R3tick"), ("IThree", "zero_R0", "zero_R3tick")):
        # as the registered estimator: each stock's days weighted equally, then stocks equally
        st = (per[x] - per[y]).dropna().groupby(level=["stock", "day"]).mean().groupby(level="stock").mean()
        for t, name in enumerate(("Small", "Mid", "Large")):
            sel = terc.reindex(st.index) == t
            macros[f"IexTail{hid}{name}Share"] = f"{100 * st[sel].sum() / st.sum():.0f}\\%"
            macros[f"IexTail{name}Stocks"] = str(int(sel.sum()))
            macros[f"IexTail{name}EpisodeShare"] = f"{100 * n_eps.reindex(st.index)[sel].sum() / n_eps.sum():.1f}\\%"
    for name in ("Small", "Mid", "Large"):
        print(f"| {name} | {macros[f'IexTail{name}Stocks']} | {macros[f'IexTail{name}EpisodeShare']} | "
              f"{macros[f'IexTailITwo{name}Share']} | {macros[f'IexTailIThree{name}Share']} |")
    with open(REPO / "paper" / f"numbers_iex_tail_{a.eval}.tex", "w") as fh:
        fh.write(f"% generated by experiments/iex_tail_check.py --eval {a.eval} -- do not edit\n")
        for k, v in sorted(macros.items()):
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


if __name__ == "__main__":
    main()
