"""The registered stock contrasts by task family (TMLR review, round 1; post hoc and exploratory).

    python experiments/family_contrasts.py [--stages stage1 stage2]

Each episode belongs to one of three task families, with its order size and horizon set in microstructure units
(MS), Kyle-Obizhaeva units (KO) or physical units (P). For each sealed Nasdaq stage, the registered stock contrasts
H2 (raw minus MS), H3 (z-scores minus MS+tick), H4 (raw with descriptors minus MS) and H6 (MS+tick minus MS) are
recomputed within each family from the stored registered evaluation, with the registered estimator (spreads per
share, seeds averaged, every stock weighted equally, cluster bootstrap over stocks stratified by relative-tick
tercile; 95% intervals). Loads each sealed episode table once through the logged loader. Writes
results/transfer/family_contrasts.json and paper/numbers_family.tex.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from confirm import policy_costs  # noqa: E402

from invex.env.units import unit_frame  # noqa: E402
from invex.eval import freeze  # noqa: E402
from invex.eval.stats import cluster_bootstrap  # noqa: E402
from invex.eval.universe import load_splits  # noqa: E402
from invex.paths import REPO, RESULTS  # noqa: E402

TESTS = {"H2": ("zero:R0", "zero:R3"), "H3": ("zero:R1", "zero:R3tick"), "H4": ("zero:R0desc", "zero:R3"),
         "H6": ("zero:R3tick", "zero:R3")}
LETTERS = {"1": "One", "2": "Two", "3": "Three", "4": "Four", "6": "Six"}


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stages", nargs="+", default=["stage1", "stage2"])
    a = ap.parse_args(argv)
    sp = load_splits()
    cuts = np.log(sp["eta_sigma_tercile_cuts"])
    out, m = {}, {}
    for stage in a.stages:
        meta = json.loads((RESULTS / "transfer" / f"eval_{stage}.json").read_text())
        eps = freeze.load(meta["episodes"], unseal=True,
                          reason=f"post hoc (review round 1): the registered stock contrasts by task family on {stage}")
        uf = unit_frame(eps, sp["ko_constants"])
        eta = pd.Series(uf["_eta_sigma"].to_numpy(), index=eps["stock"].to_numpy()).groupby(level=0).median()
        res = pd.read_parquet(RESULTS / "transfer" / f"eval_{stage}.parquet",
                              columns=["key", "policy", "stock", "day", "family", "c_spread", "excluded"])
        res = res[~res["excluded"] & res["policy"].str.match(r"^(zero_R(0|0desc|1|3|3tick)_s[0-2]|immediate)$")]
        fam = res.drop_duplicates("key").set_index("key")["family"]
        per = policy_costs(res, "c_spread", "seen")
        keys = per.index.get_level_values("key")
        out[stage] = {}
        for f in ("MS", "KO", "P"):
            sel = per[fam.reindex(keys).to_numpy() == f]
            out[stage][f] = {"episodes": int(len(sel))}
            for hid, (x, y) in TESTS.items():
                d = (sel[x] - sel[y]).dropna()
                by_stock = d.groupby(level="stock").mean()
                st = np.digitize(np.log(eta.reindex(by_stock.index).to_numpy()), cuts)
                r = cluster_bootstrap(by_stock.to_numpy(), st, n_boot=10_000, level=0.95)
                out[stage][f][hid] = {k: float(r[k]) for k in ("mean", "lo", "hi")}
                key = f"Fam{'StageOne' if stage == 'stage1' else 'StageTwo'}{f.capitalize()}H{LETTERS[hid[1]]}"
                m[key] = f"{r['mean']:+.3f}"
                m[key + "Lo"], m[key + "Hi"] = f"{r['lo']:+.3f}", f"{r['hi']:+.3f}"
                print(f"{stage} {f:2s} {hid}: {r['mean']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}] ({len(by_stock)} stocks)")
    (RESULTS / "transfer" / "family_contrasts.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/family_contrasts.py (post hoc) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_family.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
