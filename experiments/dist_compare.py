"""Distribution-level comparisons on the sealed Nasdaq stages (review round 4, R6; exploratory, post hoc).

    python experiments/dist_compare.py [--pairs RawMst] [--macros-only]

The registered tests compare mean costs. Here the whole cost distribution: for H1 (zero-shot MS+tick against the seen
MS+tick policy, on the stocks the seen policy saw) and H2 (raw units against MS units), and raw units against MS+tick (RawMst), the differences between the
two policies' per-episode cost quantiles (1st, 10th, 50th, 90th and 99th percentiles), in their expected cost in the
worst 5% of episodes (CVaR) and in their standard deviations, each policy's cost averaged over its three seeds, episodes weighted equally. 95% intervals from a
stock bootstrap (1,000 replicates; a stock's episodes are resampled together). From the stored evaluations; reads no
sealed table. Writes results/transfer/dist_compare.json and paper/numbers_dist_compare.tex.
"""

from __future__ import annotations

import json
import sys

import numpy as np
import pandas as pd
import pyarrow.dataset as ds

from invex.paths import DATA, REPO, RESULTS

STAGES = {"StageOne": "stage1", "StageTwo": "stage2"}
PAIRS = {"HOne": ("zero_R3tick", "seent_R3tick"), "HTwo": ("zero_R0", "zero_R3"),
         "RawMst": ("zero_R0", "zero_R3tick")}  # RawMst: raw units against MS+tick (review round 5, R4)
QS = {"One": 0.01, "Ten": 0.1, "Med": 0.5, "Ninety": 0.9, "Ninetynine": 0.99}
N_BOOT = 1000


def costs(ev: str, arms: tuple[str, str]) -> pd.DataFrame:
    pols = [f"{a}_s{s}" for a in arms for s in range(3)]
    t = ds.dataset(RESULTS / "transfer" / f"eval_{ev}.parquet").to_table(
        columns=["key", "policy", "stock", "c_spread", "excluded"], filter=ds.field("policy").isin(pols)).to_pandas()
    t = t[~t["excluded"]].assign(arm=lambda r: r["policy"].str.replace(r"_s\d+$", "", regex=True))
    per = t.pivot_table(index=["key", "stock"], columns="arm", values="c_spread", aggfunc="mean").dropna()
    return per.reset_index()


def wquantile(x: np.ndarray, w: np.ndarray, q: float) -> float:
    o = np.argsort(x)
    cw = np.cumsum(w[o])
    return float(x[o][np.searchsorted(cw, q * cw[-1])])


def wcvar(x: np.ndarray, w: np.ndarray, q: float = 0.95) -> float:
    o = np.argsort(x)
    xs, ws = x[o], w[o]
    cw = np.cumsum(ws)
    tail = cw > q * cw[-1]
    return float((xs[tail] * ws[tail]).sum() / ws[tail].sum())


def stats_of(a: np.ndarray, b: np.ndarray, w: np.ndarray) -> dict:
    out = {k: wquantile(a, w, q) - wquantile(b, w, q) for k, q in QS.items()}
    out["Cvar"] = wcvar(a, w) - wcvar(b, w)
    out["Mean"] = float((a * w).sum() / w.sum() - (b * w).sum() / w.sum())
    sd = lambda x: float(np.sqrt((w * (x - (x * w).sum() / w.sum()) ** 2).sum() / w.sum()))  # noqa: E731
    out["Sd"] = sd(a) - sd(b)
    return out


def write_macros(out: dict) -> None:
    m = {}
    for key, res in out.items():
        for k, r in res.items():
            mk = f"Dist{key}{k}"
            m[mk], m[mk + "Lo"], m[mk + "Hi"] = f"{r['est']:+.3f}", f"{r['lo']:+.3f}", f"{r['hi']:+.3f}"
            m[mk + "Abs"] = f"{abs(r['est']):.3f}"  # the size of the difference, for prose that states its direction
    lines = ["% generated by experiments/dist_compare.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_dist_compare.tex").write_text("\n".join(lines) + "\n")


def one_pair(tag: str, ev: str, hid: str, rng: np.random.Generator) -> dict:
    a, b = PAIRS[hid]
    df = costs(ev, (a, b))
    if hid == "HOne":
        seen = set(pd.read_parquet(DATA / "transitions" / "testseen_v0" / "eps.parquet", columns=["stock"])["stock"])
        df = df[df["stock"].isin(seen)]
    codes, uniq = pd.factorize(df["stock"])
    xa, xb = df[a].to_numpy(), df[b].to_numpy()
    point = stats_of(xa, xb, np.ones(len(df)))
    boots = {k: [] for k in point}
    for _ in range(N_BOOT):
        cnt = np.bincount(rng.integers(0, len(uniq), len(uniq)), minlength=len(uniq)).astype(float)
        r = stats_of(xa, xb, cnt[codes])
        for k, v in r.items():
            boots[k].append(v)
    res = {k: {"est": point[k], "lo": float(np.quantile(boots[k], 0.025)),
               "hi": float(np.quantile(boots[k], 0.975))} for k in point}
    print(tag, hid, {k: f"{r['est']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}]" for k, r in res.items()}, flush=True)
    return res


def _job(args):
    tag, ev, hid, i = args
    return f"{tag}{hid}", one_pair(tag, ev, hid, np.random.default_rng([0, i]))


def main() -> None:
    path = RESULTS / "transfer" / "dist_compare.json"
    if "--macros-only" in sys.argv:
        write_macros(json.loads(path.read_text()))
        return
    if "--pairs" in sys.argv:  # only the named pairs, the stages in parallel, merged into the stored results
        from concurrent.futures import ProcessPoolExecutor
        hids = sys.argv[sys.argv.index("--pairs") + 1].split(",")
        jobs = [(tag, ev, hid, i) for i, (tag, ev) in enumerate(STAGES.items()) for hid in hids]
        out = json.loads(path.read_text()) if path.exists() else {}
        with ProcessPoolExecutor(len(jobs)) as ex:
            out.update(dict(ex.map(_job, jobs)))
        path.write_text(json.dumps(out, indent=1))
        write_macros(out)
        return
    rng = np.random.default_rng(0)  # the full run: one generator in this order for H1 and H2, as first run
    out = {}
    for tag, ev in STAGES.items():
        for hid in ("HOne", "HTwo"):
            out[f"{tag}{hid}"] = one_pair(tag, ev, hid, rng)
    for i, (tag, ev) in enumerate(STAGES.items()):  # later pairs: a generator per stage, as with --pairs
        for hid in PAIRS:
            if hid not in ("HOne", "HTwo"):
                out[f"{tag}{hid}"] = one_pair(tag, ev, hid, np.random.default_rng([0, i]))
    path.write_text(json.dumps(out, indent=1))
    write_macros(out)


if __name__ == "__main__":
    main()
