"""The equal-information arm's residuals as shares of the margin (review round 3; from the stored analyses).

    python experiments/info_margin_shares.py

RAW+INFO minus MS+tick and its 95% upper bound, divided by the Nasdaq margin (0.015), from the unrounded estimates in
results/transfer/info_arm_stage{1,2}.json (experiments/info_arm.py). Reads no sealed table.
Writes paper/numbers_info_margin.tex.
"""

from __future__ import annotations

import json

from invex.paths import REPO, RESULTS

MARGIN = 0.015
STAGES = {"StageOne": "info_arm_stage1", "StageTwo": "info_arm_stage2"}
LEARNERS = ("Trees", "Nn", "Ppo")


def main() -> None:
    m = {}
    for tag, stem in STAGES.items():
        d = json.loads((RESULTS / "transfer" / f"{stem}.json").read_text())
        for lab in LEARNERS:
            r = d.get(f"{lab}InfoVsMstick")
            if r is None:
                continue
            m[f"InfoMargin{tag}{lab}"] = f"{r['mean'] / MARGIN:.2f}"
            m[f"InfoMargin{tag}{lab}Hi"] = f"{r['hi'] / MARGIN:.2f}"
            print(f"{tag} {lab}: {r['mean'] / MARGIN:.3f} of a margin (95% upper bound {r['hi'] / MARGIN:.3f})")
    lines = ["% generated by experiments/info_margin_shares.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_info_margin.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
