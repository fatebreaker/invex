"""Intervals for the IEX tests that allow for only ten day clusters (review round 4, R3; exploratory, post hoc).

    python experiments/iex_small_cluster.py [--dir supplement/registered_tests]

The registered IEX intervals come from a two-way (stocks x days) percentile bootstrap, which can undercover with ten
days. Here each estimand is written as a weighted mean of stock-day cell means, theta = sum w_sd m_sd (estimand (a):
w_sd = 1 / (S D_s); estimand (b): w_sd = n_sd / N), and its variance is estimated by two-way clustering (Cameron,
Gelbach and Miller 2011) on the linearised contributions e_sd = w_sd (m_sd - theta), with the G/(G-1) correction in
each dimension: V = S/(S-1) sum_s (sum_d e_sd)^2 + D/(D-1) sum_d (sum_s e_sd)^2 - sum_sd e_sd^2. The 95% interval
uses Student's t with D - 1 = 9 degrees of freedom, the usual small-cluster correction (Cameron and Miller 2015), and a
hypothesis "holds" when that interval clears zero or the margin of its registered test (level 2.5% one-sided, iex-v8).
Computed from the supplement's stock-day cells for the registered prospective IEX families; reads no sealed table.
Writes results/transfer/iex_small_cluster.json and paper/numbers_iex_small_cluster.tex.
"""

from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd
from scipy import stats

from invex.paths import REPO, RESULTS

FAMILIES = {"confirm_iex_test_iex": ("I1", "I2", "I3"), "confirm_iex_test_ppo_iex": ("P1", "P2", "P3"),
            "confirm_iex_test_v8_iexlm": ("P4",), "confirm_iex_test_ppo_iexlearner": ("L1", "L2"),
            "confirm_iex_test_wide_iexwide": ("W1", "W2", "W3", "W4", "W5")}
MAC = {"I1": "IOne", "I2": "ITwo", "I3": "IThree", "P1": "POne", "P2": "PTwo", "P3": "PThree", "P4": "PFour",
       "L1": "LOne", "L2": "LTwo", "W1": "WOne", "W2": "WTwo", "W3": "WThree", "W4": "WFour", "W5": "WFive"}
# the registered test of each hypothesis and its margin, for the decision at 2.5% one-sided (iex-v8)
TEST = {"I1": ("less", 0), "I2": ("noninf", 0.020), "I3": ("greater", 0), "P1": ("less", 0), "P2": ("noninf", 0.020),
        "P3": ("greater", 0), "P4": ("noninf", 0.020), "L1": ("less", 0), "L2": ("less", 0), "W1": ("greater", 0),
        "W2": ("greater", 0), "W3": ("greater", 0), "W4": ("greater", 0), "W5": ("greater", 0)}


def holds(h: str, r: dict) -> bool:
    test, delta = TEST[h]
    return {"less": r["hi"] < 0, "greater": r["lo"] > 0, "noninf": r["hi"] < delta}[test]


def cgm(cells: pd.DataFrame, estimand: str) -> dict:
    c = cells.copy()
    S, N = c["stock"].nunique(), c["n"].sum()
    if estimand == "a":
        D_s = c.groupby("stock")["day"].transform("nunique")
        c["w"] = 1.0 / (S * D_s)
    else:
        c["w"] = c["n"] / N
    theta = float((c["w"] * c["mean"]).sum())
    c["e"] = c["w"] * (c["mean"] - theta)
    D = c["day"].nunique()
    us = c.groupby("stock")["e"].sum()
    vd = c.groupby("day")["e"].sum()
    V = S / (S - 1) * float((us ** 2).sum()) + D / (D - 1) * float((vd ** 2).sum()) - float((c["e"] ** 2).sum())
    se = float(np.sqrt(max(V, 0.0)))
    t = float(stats.t.ppf(0.975, D - 1))
    return {"mean": theta, "se": se, "lo": theta - t * se, "hi": theta + t * se, "days": int(D), "stocks": int(S)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(REPO / "supplement" / "registered_tests"))
    a = ap.parse_args()
    cells = pd.read_parquet(f"{a.dir}/cells.parquet")
    out, m = {}, {}
    for stem, hyps in FAMILIES.items():
        for h in hyps:
            x = cells[(cells["analysis"] == stem) & (cells["hypothesis"] == h)]
            if x.empty:
                print(f"{stem} {h}: no cells")
                continue
            for est, tag in (("a", "Stock"), ("b", "Episode")):
                r = cgm(x, est)
                r["holds"] = holds(h, r)
                out[f"{h}:{est}"] = r
                k = f"IexSc{MAC[h]}{tag}"
                m[k], m[k + "Lo"], m[k + "Hi"] = f"{r['mean']:+.3f}", f"{r['lo']:+.3f}", f"{r['hi']:+.3f}"
                print(f"{h} ({est}): {r['mean']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}]  se {r['se']:.4f}  "
                      f"{'holds' if r['holds'] else 'not shown'}")
    for est, tag in (("a", "Stock"), ("b", "Episode")):
        held = [h for h in MAC if out.get(f"{h}:{est}", {}).get("holds")]
        m[f"IexScHeld{tag}"] = str(len(held))
        m[f"IexScHeld{tag}List"] = ", ".join(held)
        print(f"({est}) holds: {len(held)}: {held}")
    (RESULTS / "transfer" / "iex_small_cluster.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/iex_small_cluster.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_iex_small_cluster.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
