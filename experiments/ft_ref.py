"""The fine-tuned reference of the TMLR review, round 1 (exploratory, IEX validation days, unsealed).

    python experiments/ft_ref.py              # IEX validation days (unsealed)
    python experiments/ft_ref.py --test       # the IEX test days (post hoc; loads the sealed table, logged)

Compares, on the IEX validation days' one-tick books (w_onetick >= 0.5; the population of the IEX tests), the
Nasdaq-trained PPO MS+tick policies (zeroppo), the PPO policies trained on IEX by the same recipe (ixppo, iex-v8) and
the Nasdaq-trained policies fine-tuned on the same IEX episodes with the same budget (ftppo): mean costs and paired
differences in spreads per share, seeds averaged, under both IEX estimands (every stock and each of its days weighted
equally; every episode weighted equally), two-way bootstrap over stocks and days, 95% intervals.
Writes results/transfer/ft_ref.json and paper/numbers_ft_ref.tex.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from confirm import policy_costs  # noqa: E402

from invex.eval import freeze  # noqa: E402
from invex.eval.stats import pigeonhole_bootstrap  # noqa: E402
from invex.paths import REPO, RESULTS  # noqa: E402

PAIRS = {"ZeroVsIx": ("zeroppo:R3tick", "ixppo:R3tick"), "FtVsIx": ("ftppo:R3tick", "ixppo:R3tick"),
         "FtVsZero": ("ftppo:R3tick", "zeroppo:R3tick")}


def tables(diff: pd.Series, by: str):
    g = diff.groupby(level=["stock", "day"])
    if by == "episode":
        return g.sum().unstack().fillna(0.0).to_numpy(), g.count().unstack().fillna(0.0).to_numpy()
    cm = g.mean().unstack()
    w = cm.notna().astype(float)
    w = w.div(w.sum(axis=1), axis=0)
    return (cm.fillna(0.0) * w).to_numpy(), w.to_numpy()


def main() -> None:
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", action="store_true")
    args = ap.parse_args()
    cols = ["key", "policy", "stock", "day", "c_spread", "excluded"]
    if args.test:
        eps = freeze.load("iex_test_v0", unseal=True, reason="post hoc (review round 1): the fine-tuned PPO reference "
                                                             "on the IEX test days (exploratory)")
        res = pd.concat([pd.read_parquet(RESULTS / "transfer" / f"eval_{e}.parquet", columns=cols)
                         for e in ("iex_test_v8", "iex_test_ft")], ignore_index=True)
    else:
        eps = freeze.load("iex_val_v0")
        res = pd.read_parquet(RESULTS / "transfer" / "eval_iex_val_v0_ft.parquet", columns=cols)
    keep = set(eps.loc[eps["w_onetick"] >= 0.5, "key"])
    res = res[~res["excluded"] & res["key"].isin(keep)]
    per = policy_costs(res, "c_spread", "seen")
    out, m = {"episodes": int(len(per)), "stocks": int(per.index.get_level_values("stock").nunique())}, {}
    for col in ("zeroppo:R3tick", "ixppo:R3tick", "ftppo:R3tick"):
        v = per[col].dropna()
        out[col] = {"by_episode": float(v.mean()), "by_stock": float(v.groupby(level="stock").mean().mean())}
        m["FtCost" + {"zeroppo:R3tick": "Zero", "ixppo:R3tick": "Ix", "ftppo:R3tick": "Ft"}[col]] = f"{v.mean():.3f}"
    for label, (a, b) in PAIRS.items():
        d = (per[a] - per[b]).dropna()
        for by, tag in (("stock", "Stock"), ("episode", "Episode")):
            r = pigeonhole_bootstrap(*tables(d, by), n_boot=10_000, level=0.95)
            out[f"{label}_{by}"] = {k: float(r[k]) for k in ("mean", "lo", "hi")}
            m[f"Ft{label}{tag}"] = f"{r['mean']:+.3f}"
            m[f"Ft{label}{tag}Lo"], m[f"Ft{label}{tag}Hi"] = f"{r['lo']:+.3f}", f"{r['hi']:+.3f}"
            print(f"{label:9s} {by:8s} {r['mean']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}]")
    m["FtEpisodes"] = f"{out['episodes']:,}".replace(",", "{,}")
    m["FtStocks"] = str(out["stocks"])
    if args.test:  # the same macros, prefixed for the test days
        m = {"FtTest" + k[2:]: v for k, v in m.items()}
    sfx = "_test" if args.test else ""
    (RESULTS / "transfer" / f"ft_ref{sfx}.json").write_text(json.dumps(out, indent=1))
    lines = [f"% generated by experiments/ft_ref.py {'--test ' if args.test else ''}(exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / f"numbers_ft_ref{sfx}.tex").write_text("\n".join(lines) + "\n")
    print(json.dumps({k: out[k] for k in ("zeroppo:R3tick", "ixppo:R3tick", "ftppo:R3tick")}, indent=1))


if __name__ == "__main__":
    main()
