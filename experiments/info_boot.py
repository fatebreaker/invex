"""The equal-information arm across training samples (review round 3; exploratory, validation only).

    python experiments/info_boot.py

R0info (raw features plus the window statistics, cost in spreads), R0 (raw units) and R0r (raw features, cost in
spreads) against R3tick (MS+tick) for the tree learner, on the validation days, for each of the 20 refits on
stock-bootstrap resamples of the training split (tag zboot; refit k of every representation uses the same resample),
and for the training seeds on the fixed training set (tag zero). Each contrast is the mean over validation stocks of
the per-stock cost difference (stocks weighted equally, as in analyze_boot.py). Reports the mean, standard deviation
and range across refits, the standard deviation across seeds, and the share of the raw-unit loss that R0info closes
in each refit. Reads only stored evaluations. Writes results/transfer/info_boot.json and paper/numbers_info_boot.tex.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from invex.paths import REPO, RESULTS

OUT = RESULTS / "transfer"
BOOT_EVALS = ["val_v0_boot", "val_v0_boot2", "val_v0_boot_info"]
SEED_EVALS = ["val_v0", "val_v0_info"]
CONTRASTS = [("InfoVsMstick", "R0info", "R3tick"), ("RawVsMstick", "R0", "R3tick"), ("RawrVsMstick", "R0r", "R3tick")]


def load(evals: list[str], tag: str) -> pd.DataFrame:
    parts = []
    for ev in evals:
        r = pd.read_parquet(OUT / f"eval_{ev}.parquet", columns=["policy", "stock", "c_spread", "excluded"])
        parts.append(r[r["policy"].str.startswith(tag + "_") & ~r["excluded"]])
    r = pd.concat(parts, ignore_index=True)
    return r.groupby(["policy", "stock"])["c_spread"].mean()  # per-stock mean cost of each policy


def contrast(per: pd.Series, tag: str, a: str, b: str, seed: int) -> float | None:
    pa, pb = f"{tag}_{a}_s{seed}", f"{tag}_{b}_s{seed}"
    if pa not in per.index.get_level_values(0) or pb not in per.index.get_level_values(0):
        return None
    return float((per.loc[pa] - per.loc[pb]).dropna().mean())


def main() -> None:
    out, m = {}, {}
    for tag, evals, seeds in (("zboot", BOOT_EVALS, range(20)), ("zero", SEED_EVALS, range(3))):
        per = load(evals, tag)
        vals = {}
        for label, a, b in CONTRASTS:
            vals[label] = {s: v for s in seeds if (v := contrast(per, tag, a, b, s)) is not None}
        common = sorted(set(vals["InfoVsMstick"]) & set(vals["RawVsMstick"]))
        share = {s: 1 - vals["InfoVsMstick"][s] / vals["RawVsMstick"][s] for s in common if vals["RawVsMstick"][s] > 0}
        out[tag] = {"values": vals, "share_closed": share}
        for label, v in vals.items():
            x = np.array(list(v.values()))
            if len(x) < 2:
                continue
            s = {"n": int(len(x)), "mean": float(x.mean()), "sd": float(x.std(ddof=1)), "min": float(x.min()),
                 "max": float(x.max())}
            out[tag][label] = s
            k = f"InfoBoot{'Refit' if tag == 'zboot' else 'Seed'}{label}"
            m[k + "Mean"], m[k + "Sd"] = f"{s['mean']:+.3f}", f"{s['sd']:.4f}"
            m[k + "Min"], m[k + "Max"] = f"{s['min']:+.3f}", f"{s['max']:+.3f}"
            print(f"{tag:5s} {label:13s} n={s['n']:2d} mean {s['mean']:+.4f} sd {s['sd']:.4f} "
                  f"range [{s['min']:+.4f}, {s['max']:+.4f}]")
        if share:
            sh = np.array(list(share.values()))
            k = f"InfoBoot{'Refit' if tag == 'zboot' else 'Seed'}Share"
            m[k + "Min"], m[k + "Max"] = f"{100 * sh.min():.0f}\\%", f"{100 * sh.max():.0f}\\%"
            m[k + "Median"] = f"{100 * np.median(sh):.0f}\\%"
            print(f"{tag:5s} share of the raw-unit loss closed: median {np.median(sh):.0%}, range "
                  f"[{sh.min():.0%}, {sh.max():.0%}]")
    r, z = out["zboot"].get("InfoVsMstick"), out["zero"].get("InfoVsMstick")
    if r and z:  # training-sample variation beyond the seeds'
        excess = float(np.sqrt(max(0.0, r["sd"] ** 2 - z["sd"] ** 2)))
        out["train_sd_info"] = excess
        m["InfoBootTrainSd"] = f"{excess:.4f}"
        m["InfoBootRefits"] = str(r["n"])
        raw = out["zboot"]["RawVsMstick"]  # the share of the refits' average raw-unit loss that R0info closes
        m["InfoBootRefitShareOfMean"] = f"{100 * (1 - r['mean'] / raw['mean']):.0f}\\%"
    (OUT / "info_boot.json").write_text(json.dumps(out, indent=1, default=str))
    lines = ["% generated by experiments/info_boot.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_info_boot.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
