"""Two draws of start times on the same IEX days (review round 3; exploratory, post hoc, from the supplement's inputs).

    python experiments/iex_two_draws.py [--dir supplement/registered_tests]

The registered interim look drew its own start times on the first five test days (a deviation, App. K), so its
tables and the final tables restricted to those days are two independent draws on almost the same stock-days. For
I1-I3, under the two registered estimands ((a) every stock and each of its days weighted equally, (b) every episode
weighted equally): the estimate from each draw on 19-23 October, and the final draw's without NHP. Point estimates
only, from the stock-day cells; reads no sealed table.
Writes results/transfer/iex_two_draws.json and paper/numbers_iex_two_draws.tex.
"""

from __future__ import annotations

import argparse
import json

import pandas as pd

from invex.paths import REPO, RESULTS

DRAWS = {"Final": "confirm_iex_test_iex", "Interim": "confirm_iex_interim_iex"}
HYPS = {"I1": "IOne", "I2": "ITwo", "I3": "IThree"}
DIAG_STOCK = "NHP"


def estimates(c: pd.DataFrame) -> dict:
    """(a): the mean over stocks of each stock's mean over its days of the day means; (b): the mean over episodes."""
    return {"a": float(c.groupby("stock")["mean"].mean().mean()), "b": float(c["sum"].sum() / c["n"].sum())}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(REPO / "supplement" / "registered_tests"))
    a = ap.parse_args()
    cells = pd.read_parquet(f"{a.dir}/cells.parquet")
    days = sorted(cells.loc[cells["analysis"] == DRAWS["Interim"], "day"].unique())
    out, m = {"days": [str(d) for d in days]}, {}
    cells_of = {}
    for draw, stem in DRAWS.items():
        c = cells[(cells["analysis"] == stem) & cells["day"].isin(days)]
        cells_of[draw] = set(map(tuple, c.loc[c["hypothesis"] == "I2", ["stock", "day"]].to_numpy()))
        for h, mac in HYPS.items():
            ch = c[c["hypothesis"] == h]
            r = estimates(ch)
            out[f"{draw}{h}"] = r
            if draw == "Final":
                out[f"FinalNoNhp{h}"] = estimates(ch[ch["stock"] != DIAG_STOCK])
            for k, est in (("Stock", "a"), ("Episode", "b")):
                m[f"IexDraws{draw}{mac}{k}"] = f"{r[est]:+.3f}"
            if draw == "Final":
                m[f"IexDrawsFinalNoNhp{mac}Stock"] = f"{out[f'FinalNoNhp{h}']['a']:+.3f}"
                m[f"IexDrawsFinalNoNhp{mac}Episode"] = f"{out[f'FinalNoNhp{h}']['b']:+.3f}"
            print(f"{draw:8s} {h}: (a) {r['a']:+.3f}  (b) {r['b']:+.3f}" +
                  (f"  without {DIAG_STOCK} (a) {out[f'FinalNoNhp{h}']['a']:+.3f}" if draw == "Final" else ""))
    final, interim = cells_of["Final"], cells_of["Interim"]
    out["stock_days"] = {"both": len(final & interim), "final_only": len(final - interim),
                         "interim_only": len(interim - final)}
    for k, v in out["stock_days"].items():
        m["IexDrawsStockDays" + k.title().replace("_", "")] = f"{v:,}".replace(",", "{,}")
    a_moves = [abs(out[f"Final{h}"]["a"] - out[f"Interim{h}"]["a"]) for h in HYPS]
    b_moves = [abs(out[f"Final{h}"]["b"] - out[f"Interim{h}"]["b"]) for h in HYPS]
    m["IexDrawsStockMoveMin"], m["IexDrawsStockMoveMax"] = f"{min(a_moves):.2f}", f"{max(a_moves):.2f}"
    m["IexDrawsEpisodeMoveMax"] = f"{max(b_moves):.3f}"
    print(f"stock-days {out['stock_days']}; (a) moves {min(a_moves):.3f}-{max(a_moves):.3f}, (b) at most {max(b_moves):.3f}")
    (RESULTS / "transfer" / "iex_two_draws.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/iex_two_draws.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_iex_two_draws.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
