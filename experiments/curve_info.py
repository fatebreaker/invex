"""The learning curve of the equal-information arm (review round 3; exploratory, validation only).

    python experiments/curve_info.py

R0info (raw features plus the window statistics, cost in spreads; trees) trained on the learning curve's subsets of
the training transitions (experiments/learning_curve.py fit --reps R0info, models curve_R0infon<size>_s<seed>), next
to R3tick and R0 on the same subsets. The cost of each (representation, size) is the mean over validation episodes
of the seed-averaged cost in spreads, as in learning_curve.py analyze, whose R3tick and R0 values this script
reproduces as a check. Reads only stored evaluations. Writes results/transfer/curve_info.json and
paper/numbers_curve_info.tex.
"""

from __future__ import annotations

import json
import re

import pandas as pd

from invex.paths import REPO, RESULTS

OUT = RESULTS / "transfer"
SIZES = {1000: "OneK", 3000: "ThreeK", 10_000: "TenK", 30_000: "ThirtyK", 100_000: "HundredK", 376_610: "Full"}
REPS = {"R3tick": "MsTick", "R0": "Raw", "R0info": "Info"}
PAT = re.compile(r"^curve_(?P<rep>[A-Za-z0-9]+?)n(?P<n>\d+)_s(?P<seed>\d+)$")


def costs() -> dict:
    cur = pd.concat([pd.read_parquet(OUT / f"eval_{ev}.parquet", columns=["key", "policy", "c_spread", "excluded"])
                     for ev in ("val_v0_curve", "val_v0_curve_info")], ignore_index=True)
    full = pd.concat([pd.read_parquet(OUT / f"eval_{ev}.parquet", columns=["key", "policy", "c_spread", "excluded"])
                      for ev in ("val_v0", "val_v0_info")], ignore_index=True)
    out = {}
    m = cur["policy"].str.extract(PAT)
    cur = cur.assign(rep=m["rep"], n=pd.to_numeric(m["n"])).dropna(subset=["rep"])
    for (rep, n), g in cur.groupby(["rep", "n"]):
        out[(rep, int(n))] = float(g.groupby("key")["c_spread"].mean().mean())
    for rep in REPS:
        g = full[full["policy"].str.match(rf"^zero_{rep}_s\d+$")]
        out[(rep, 376_610)] = float(g.groupby("key")["c_spread"].mean().mean())
    return out


def main() -> None:
    c = costs()
    m, table = {}, {}
    for rep, R in REPS.items():
        for n, N in SIZES.items():
            if (rep, n) in c:
                m[f"CurveInfo{R}{N}"] = f"{c[(rep, n)]:.3f}"
                table[f"{rep}:{n}"] = c[(rep, n)]
    for n in SIZES:
        row = "  ".join(f"{rep} {c[(rep, n)]:.4f}" for rep in REPS if (rep, n) in c)
        print(f"n={n:>7,}: {row}")
    # the check against learning_curve.py's macros (paper/numbers_curve*.tex)
    old = {}
    for f in (REPO / "paper").glob("numbers*.tex"):
        for k, v in re.findall(r"\\newcommand\{\\(Curve(?:MsTick|Raw)[A-Za-z]+)\}\{([0-9.]+)\}", f.read_text()):
            old[k] = float(v)
    for k, v in m.items():
        ok = k.replace("CurveInfo", "Curve")
        if ok in old and abs(old[ok] - float(v)) > 0.0005:
            raise SystemExit(f"{k} = {v} does not reproduce {ok} = {old[ok]}")
    (OUT / "curve_info.json").write_text(json.dumps(table, indent=1))
    lines = ["% generated by experiments/curve_info.py (post hoc, exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items()) if k.startswith("CurveInfoInfo")]
    (REPO / "paper" / "numbers_curve_info.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
