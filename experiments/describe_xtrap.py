"""Who the Stage 1 stocks outside each restricted training range are: the span of trading activity outside the
activity range, and the price and relative tick of the stocks with larger trades than any in training.

    python experiments/describe_xtrap.py

Reads the stored Stage 1 evaluation (one policy's rows; no sealed table) and results/transfer/xtrap_<stat>_fit.json.
Writes paper/numbers_xtrap_desc.tex (prefix XtrapDesc).
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from invex.paths import REPO, RESULTS

OUT = RESULTS / "transfer"


def main() -> None:
    cols = ["key", "policy", "stock", "w_trades", "w_seconds", "w_volume", "w_mid", "tick", "eta", "excluded"]
    r = pd.read_parquet(OUT / "eval_stage1_rev.parquet", columns=cols)
    r = r[(r["policy"] == r["policy"].iloc[0]) & ~r["excluded"]]
    s = r.groupby("stock").agg(act=("w_trades", "median"), sec=("w_seconds", "median"), vol=("w_volume", "median"),
                               mid=("w_mid", "median"), tick=("tick", "median"), eta=("eta", "median"))
    s["activity"] = s["act"] / s["sec"]
    s["tradesize"] = s["vol"] / s["act"].clip(lower=1)
    s["price"] = s["mid"] / 1e4  # ITCH prices in 1e-4 dollars
    m = {}
    fa = json.loads((OUT / "xtrap_activity_fit.json").read_text())
    out_a = s[(s["activity"] < fa["q25"]) | (s["activity"] > fa["q75"])]["activity"]
    lo, hi = np.percentile(out_a, [5, 95])
    m["XtrapDescActivityOutsideRatio"] = f"{hi / lo:.0f}"
    m["XtrapDescActivityRangeRatio"] = f"{fa['q75'] / fa['q25']:.1f}"
    ft = json.loads((OUT / "xtrap_tradesize_fit.json").read_text())
    above = s["tradesize"] > ft["q75"]
    m["XtrapDescTradesizeAbovePrice"] = f"{s.loc[above, 'price'].median():.2f}"
    m["XtrapDescTradesizeOtherPrice"] = f"{s.loc[~above, 'price'].median():.2f}"
    m["XtrapDescTradesizeAboveEta"] = f"{s.loc[above, 'eta'].median():.2f}"
    m["XtrapDescTradesizeOtherEta"] = f"{s.loc[~above, 'eta'].median():.2f}"
    for k, v in m.items():
        print(f"{k:36s} {v}")
    with open(REPO / "paper" / "numbers_xtrap_desc.tex", "w") as fh:
        fh.write("% generated by experiments/describe_xtrap.py -- do not edit\n")
        for k, v in sorted(m.items()):
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


if __name__ == "__main__":
    main()
