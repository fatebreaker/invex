"""The main contrasts for orders small relative to the book (review round 2; exploratory, validation days only).

    python experiments/small_orders.py

A non-intrusive replay is closest to right for orders small relative to the displayed depth. On the validation table
val_v0 (unsealed), episodes are split by the order's size over the trailing window's mean touch depth (w_depth):
at most a quarter, or more. In each stratum: the paired contrasts of H2 (raw minus MS units), H3 (z-scores minus
MS+tick), H4 (raw units with descriptors minus MS), H6 (MS+tick minus MS) and the learned MS+tick policy minus posting
and waiting, for the registered tree policies (seeds averaged per episode), every stock weighted equally, stock
bootstrap stratified by relative-tick tercile, 95% intervals.
Writes results/transfer/small_orders.json and paper/numbers_small_orders.tex.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from info_arm import costs  # noqa: E402

from invex.env.units import unit_frame  # noqa: E402
from invex.eval import freeze  # noqa: E402
from invex.eval.stats import cluster_bootstrap  # noqa: E402
from invex.eval.universe import load_splits  # noqa: E402
from invex.paths import REPO, RESULTS  # noqa: E402

CONTRASTS = [("HTwo", "zero:R0", "zero:R3"), ("HThree", "zero:R1", "zero:R3tick"), ("HFour", "zero:R0desc", "zero:R3"),
             ("HSix", "zero:R3tick", "zero:R3"), ("VsPost", "zero:R3tick", "base:post_then_cross")]
CUT = 0.25


def main() -> None:
    eps = freeze.load("val_v0")
    sp = load_splits()
    uf = unit_frame(eps, sp["ko_constants"])
    eta = eps.assign(eta=uf["_eta_sigma"].to_numpy()).groupby("stock")["eta"].median()
    small = (eps["Q"] / eps["w_depth"].clip(lower=1.0)).to_numpy() <= CUT
    strata = {"Small": set(eps.loc[small, "key"]), "Large": set(eps.loc[~small, "key"])}
    df = costs(["val_v0"])
    out, m = {"share_small": float(small.mean())}, {"SmallOrderShare": f"{100 * small.mean():.0f}\\%"}
    for sname, keys in strata.items():
        sub = df[df.index.isin(keys)]
        out[sname] = {"episodes": int(len(sub)), "stocks": int(sub["stock"].nunique())}
        for label, a, b in CONTRASTS:
            d = (sub[a] - sub[b]).dropna()
            by_stock = d.groupby(sub.loc[d.index, "stock"]).mean()
            st = np.digitize(np.log(eta.reindex(by_stock.index).to_numpy()), np.log(sp["eta_sigma_tercile_cuts"]))
            r = cluster_bootstrap(by_stock.to_numpy(), st, n_boot=10_000, level=0.95)
            out[sname][label] = {k: float(r[k]) for k in ("mean", "lo", "hi")}
            k = f"SmallOrder{sname}{label}"
            m[k], m[k + "Lo"], m[k + "Hi"] = f"{r['mean']:+.3f}", f"{r['lo']:+.3f}", f"{r['hi']:+.3f}"
            print(f"{sname:6s} {label:7s} {r['mean']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}] ({len(by_stock)} stocks)")
        m[f"SmallOrder{sname}Episodes"] = f"{len(sub):,}".replace(",", "{,}")
    (RESULTS / "transfer" / "small_orders.json").write_text(json.dumps(out, indent=1))
    lines = ["% generated by experiments/small_orders.py (exploratory) -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_small_orders.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
