"""The market regime of the data days (review round 1): the price grid and the round lots.

    python experiments/regime_check.py

* Ticks: displayed prices off the one-cent grid (sub-dollar prices excepted), summed over every built ITCH and IEX day
  from the book checks (data/<venue>/<day>/book_qa.json).
* Round lots: the eligibility rule asks for a 100-share round lot (src/invex/eval/universe.py). Since November 2025
  higher-priced stocks have round lots of 40 or 10 shares, so the rule drops them. Counts the stock-days that pass every
  other eligibility condition and fail only this one: test-split stocks at Stage 1 and Stage 2, every stock on the IEX
  test days. Day statistics only; no sealed table is read.
Writes paper/numbers_regime.tex.
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from invex.eval.universe import load_splits
from invex.paths import DATA, REPO

STAGE1 = ["2020-01-30", "2021-07-13", "2021-08-13"]
STAGE2 = ["2025-12-08", "2025-12-09", "2025-12-10", "2025-12-11", "2025-12-12", "2026-05-15", "2026-05-18", "2026-06-12"]
IEX_TEST = ["2026-10-19", "2026-10-20", "2026-10-21", "2026-10-22", "2026-10-23", "2026-10-26", "2026-10-27",
            "2026-10-28", "2026-10-29", "2026-10-30"]


def round_lot_drops(venue: str, days: list[str], pool) -> dict:
    kept = dropped = 0
    names, prices = set(), []
    for d in days:
        st = pd.read_parquet(DATA / venue / d / "daystats.parquet")
        if pool is not None:
            st = st[st["stock"].isin(pool)]
        other = (st["vwap"] >= 2.0) & (st["trades"] >= 500) & np.isfinite(st["eta_sigma"])
        rl = other & (st["round_lot"] != 100)
        kept += int((other & (st["round_lot"] == 100)).sum())
        dropped += int(rl.sum())
        names |= set(st.loc[rl, "stock"])
        prices += st.loc[rl, "vwap"].tolist()
    return {"kept": kept, "dropped": dropped, "share": dropped / max(kept + dropped, 1), "stocks": len(names),
            "median_price": float(np.median(prices)) if prices else 0.0}


def main() -> None:
    m = {}
    for venue, label in (("itch", "Itch"), ("iex", "Iex")):
        rows = off = days = 0
        for f in sorted((DATA / venue).glob("*/book_qa.json")):
            t = json.loads(f.read_text())["totals"]
            rows += t["rows"]
            off += t["off_tick"]
            days += 1
        m[f"OffTick{label}"] = str(off)
        m[f"OffTick{label}Rows"] = f"{rows / 1e9:.1f}~billion"
        m[f"OffTick{label}Days"] = str(days)
    test = {s for s, v in load_splits()["split"].items() if v == "test"}
    for days, pool, label in ((STAGE1, test, "StageOne"), (STAGE2, test, "StageTwo"), (IEX_TEST, None, "IexTest")):
        r = round_lot_drops("iex" if label == "IexTest" else "itch", days, pool)
        m[f"RoundLot{label}Share"] = f"{100 * r['share']:.1f}\\%"
        m[f"RoundLot{label}Stocks"] = str(r["stocks"])
        m[f"RoundLot{label}MedianPrice"] = f"{r['median_price']:.0f}"
        print(label, r)
    lines = ["% generated by experiments/regime_check.py -- do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REPO / "paper" / "numbers_regime.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
