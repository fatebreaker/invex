"""The secondary, exploratory analysis of the crypto replication (prereg/crypto_replication_v1.md): the registered
crypto family on the 34 days of crypto_test_v0 and crypto_rep_v0 pooled, with the estimator and two-way bootstrap of
experiments/confirm.py.

    python experiments/pool_crypto.py

Writes results/transfer/pool_crypto.json and paper/numbers_pool_crypto.tex (prefix CryptoPool).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import confirm as C  # noqa: E402

from invex.env.units import unit_frame  # noqa: E402
from invex.eval import freeze  # noqa: E402
from invex.eval.stats import boot_p, holm  # noqa: E402
from invex.eval.universe import load_splits  # noqa: E402
from invex.paths import REPO, RESULTS  # noqa: E402
from invex.provenance import provenance, write_json  # noqa: E402

EVALS = ("crypto_test", "crypto_rep")
REASON = "pooled exploratory analysis of the crypto test and its replication (crypto-rep-v1, secondary)"


def costs(ev: str) -> pd.DataFrame:
    meta = json.loads((RESULTS / "transfer" / f"eval_{ev}.json").read_text())
    eps = freeze.load(meta["episodes"], unseal=True, reason=REASON)
    uf = unit_frame(eps, load_splits()["ko_constants"])
    eps = eps.assign(sigma_trade=uf["_sigma_trade"].to_numpy())
    res = pd.read_parquet(RESULTS / "transfer" / f"eval_{ev}.parquet")
    if "excluded" in res:
        res = res[~res["excluded"]]
    res = res.drop(columns=["sigma_trade"], errors="ignore").merge(eps[["key", "sigma_trade"]], on="key")
    res["c_sigma"] = res["cost"] / (res["Q"] * res["sigma_trade"])
    # the frozen prereg-v1 policies only (seeds 0-2), as in both registered evaluations
    res = res[~res["policy"].str.match(r"^zero_.*_s[3-9]$")]
    return C.policy_costs(res, "c_sigma", "seen")  # the crypto spec names cbseen directly, as confirm.py runs it


def main() -> None:
    spec = json.loads((REPO / "prereg" / "confirmatory_v1.json").read_text())
    fam, alpha = spec["families"]["crypto"], spec.get("alpha", 0.05)
    per = pd.concat([costs(ev) for ev in EVALS])
    out = {"evals": EVALS, "episodes": int(per.shape[0]),
           "days": int(per.index.get_level_values("day").nunique()), "hypotheses": [], "provenance": provenance()}
    for h in fam["hypotheses"]:
        diff = (per[h["a"]] - per[h["b"]]).dropna()
        level = 0.90 if h["test"] in ("tost", "noninferior") else 1 - 2 * alpha
        delta = h.get("delta", spec.get("delta", 0.0))
        r = C.two_way_boots(diff, 10_000, level)
        p = boot_p(r.pop("boots"), h["test"], delta)
        out["hypotheses"].append({**h, "delta": delta, "level": level, "estimate": r, "p": p})
    for x, padj in zip(out["hypotheses"], holm([x["p"] for x in out["hypotheses"]])):
        x["p_holm"], x["supported"] = float(padj), bool(padj < alpha)
    write_json(RESULTS / "transfer" / "pool_crypto.json", out)
    macros = {"CryptoPoolDays": str(out["days"]), "CryptoPoolEpisodes": f"{out['episodes']:,}".replace(",", "{,}")}
    for x in out["hypotheses"]:
        H = "CryptoPool" + C.mname(x["id"])
        e = x["estimate"]
        macros[H + "All"], macros[H + "AllLo"], macros[H + "AllHi"] = (f"{e[k]:+.3f}" for k in ("mean", "lo", "hi"))
        macros[H + "Pholm"] = f"{x['p_holm']:.3f}"
        print(f"{x['id']}: {e['mean']:+.4f} [{e['lo']:+.4f}, {e['hi']:+.4f}] Holm p {x['p_holm']:.4f} "
              f"{'supported' if x['supported'] else 'not supported'}")
    with open(REPO / "paper" / "numbers_pool_crypto.tex", "w") as fh:
        fh.write("% generated by experiments/pool_crypto.py -- do not edit\n")
        for k, v in sorted(macros.items()):
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


if __name__ == "__main__":
    main()
