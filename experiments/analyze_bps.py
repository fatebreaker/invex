"""Economic size of the gains on an evaluation, in basis points of the price: paper/numbers_bps_<eval>.tex.

    python experiments/analyze_bps.py --eval stage1 --macro-prefix StageOne

The pooled zero-shot MS+tick policy (seeds averaged) against posting then crossing and against crossing
immediately, per-stock means of the paired difference, stock-cluster bootstrap. Also the mix of tick regimes: the
median over stocks of each stock's median spread in ticks and in bps, and the share of one-tick stocks. Sealed tables are read through the
logged loader.
"""

from __future__ import annotations

import argparse

import pandas as pd

from invex.eval.stats import cluster_bootstrap
from invex.paths import REPO, RESULTS


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--eval", required=True)
    ap.add_argument("--macro-prefix", required=True)
    a = ap.parse_args()
    res = pd.read_parquet(RESULTS / "transfer" / f"eval_{a.eval}.parquet",
                          columns=["key", "policy", "stock", "c_bps", "excluded", "w_spread", "w_mid", "tick"])
    res = res[~res["excluded"]]
    z = res[res["policy"].str.match(r"^zero_R3tick_s\d+$")].groupby("key")["c_bps"].mean().rename("z")
    m = {}
    for b, stem in (("post_then_cross", "GainBpsPost"), ("immediate", "GainBpsImmediate")):
        bb = res[res["policy"] == b].set_index("key")[["c_bps", "stock"]].join(z)
        ci = cluster_bootstrap((bb["c_bps"] - bb["z"]).groupby(bb["stock"]).mean().dropna().to_numpy(), n_boot=10_000)
        m[a.macro_prefix + stem], m[a.macro_prefix + stem + "Lo"], m[a.macro_prefix + stem + "Hi"] = (
            f"{ci[x]:.2f}" for x in ("mean", "lo", "hi"))
    post = res[res["policy"] == "post_then_cross"].groupby("stock")["c_bps"].mean()
    m[a.macro_prefix + "PostCostBps"] = f"{post.mean():.2f}"
    # the mix of tick regimes: each stock's median window spread, in ticks and in bps
    b = res[res["policy"] == "post_then_cross"]
    st = (b["w_spread"] / b["tick"]).groupby(b["stock"]).median()
    m[a.macro_prefix + "MedianSpreadTicks"] = f"{st.median():.1f}"
    m[a.macro_prefix + "OneTickShare"] = f"{100 * (st < 1.5).mean():.0f}\\%"
    m[a.macro_prefix + "MedianSpreadBps"] = f"{(1e4 * b['w_spread'] / b['w_mid']).groupby(b['stock']).median().median():.1f}"
    with open(REPO / "paper" / f"numbers_bps_{a.eval}.tex", "w") as fh:
        fh.write(f"% generated by experiments/analyze_bps.py --eval {a.eval} -- do not edit\n")
        for k, v in sorted(m.items()):
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(m)


if __name__ == "__main__":
    main()
